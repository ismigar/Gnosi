import { expect, test } from '@playwright/test';
import { settleVisualState } from '../../support/visual-state.ts';
import { acceptanceState } from '../../support/acceptance-state.ts';

for (const theme of ['light', 'dark']) {
test(`website and hosting management persist creation and confirmed removal in ${theme}`, async ({ page }, testInfo) => {
  const state = acceptanceState();
  await page.addInitScript(selected => { localStorage.setItem('i18nextLng', 'en'); localStorage.setItem('db-theme', selected); }, theme);
  await page.goto(`/@${state.primary_vault.slug}/websites`);
  await page.getByRole('button', { name: 'Create website', exact: true }).click();
  const creation = page.getByRole('dialog', { name: 'Create website', exact: true });
  await creation.getByRole('textbox').fill('Disposable management website');
  const created = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/vault/sites'));
  await creation.getByRole('button', { name: 'Create', exact: true }).click();
  expect((await created).status()).toBe(201);
  await expect(creation).toBeHidden();
  await page.getByRole('button', { name: 'Manage hosting', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Hosting', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Delete hosting', exact: true }).click();
  const removeHosting = page.getByRole('dialog', { name: 'Delete hosting', exact: true });
  await removeHosting.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Delete hosting', exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: 'Delete hosting', exact: true }).click();
  const removedHosting = page.waitForResponse(response => response.request().method() === 'PUT' && /\/api\/vault\/sites\/[^/?]+$/.test(response.url()));
  await removeHosting.getByRole('button', { name: 'Delete', exact: true }).click();
  expect((await removedHosting).ok()).toBe(true);
  await expect(page.locator('.websites-empty').filter({ hasText: 'This website has no hosting yet. Add hosting to publish.' }).first()).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Manage hosting', exact: true }).click();
  await expect(page.locator('.websites-empty').filter({ hasText: 'This website has no hosting yet. Add hosting to publish.' }).first()).toBeVisible();
  await settleVisualState(page);
  await page.screenshot({ path: testInfo.outputPath(`hosting-empty-${theme}.png`), fullPage: true });
  await page.getByRole('button', { name: 'Add hosting', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Delete hosting', exact: true })).toBeEnabled();
  await settleVisualState(page);
  await page.screenshot({ path: testInfo.outputPath(`hosting-management-${theme}.png`), fullPage: true });
  await page.getByRole('button', { name: 'Delete website', exact: true }).click();
  const removal = page.getByRole('dialog', { name: 'Delete website', exact: true });
  await expect(removal).toContainText('published files will be kept');
  await removal.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Delete website', exact: true }).click();
  await settleVisualState(page);
  await page.screenshot({ path: testInfo.outputPath(`website-removal-confirmation-${theme}.png`), fullPage: true });
  const deleted = page.waitForResponse(response => response.request().method() === 'DELETE' && response.url().includes('/api/vault/sites/'));
  await removal.getByRole('button', { name: 'Delete', exact: true }).click();
  expect((await deleted).status()).toBe(204);
  await expect(page.getByRole('button', { name: 'Delete website', exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Delete website', exact: true })).toHaveCount(0);
});
}

test('website file references upload through a modal, preview and persist', async ({ page }, testInfo) => {
  const state = acceptanceState();
  await page.addInitScript(() => { localStorage.setItem('i18nextLng', 'en'); });
  await page.goto(`/@${state.primary_vault.slug}/websites`);
  await page.getByRole('button', { name: 'Create website', exact: true }).click();
  const create = page.getByRole('dialog', { name: 'Create website', exact: true });
  await create.getByRole('textbox').fill('Disposable file website');
  await create.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(create).toBeHidden();
  await page.getByRole('tab', { name: 'Navigation & languages', exact: true }).click();
  const languages = page.locator('div[role="combobox"][aria-label="Languages"]'); await languages.press('Enter');
  await page.getByRole('option', { name: /Deutsch/u }).waitFor();
  await settleVisualState(page);
  await page.screenshot({ path: testInfo.outputPath('website-language-multiselect.png'), fullPage: true });
  await page.getByRole('option', { name: /Deutsch/u }).click(); await page.getByRole('heading', { name: 'Website settings', exact: true }).click();
  await expect(languages).toContainText('Deutsch');
  await page.getByRole('tab', { name: 'Forms', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Forms', exact: true })).toBeVisible();
  const form = page.locator('details.websites-form').first();
  await form.getByLabel('Title', { exact: true }).fill('Retained form title');
  await form.locator('summary').click(); await expect(form).not.toHaveAttribute('open', '');
  await form.locator('summary').click(); await expect(form.getByLabel('Title', { exact: true })).toHaveValue('Retained form title');
  await page.getByRole('tab', { name: 'Appearance', exact: true }).click();
  await page.getByRole('button', { name: 'Upload Logo', exact: true }).click();
  const logoDialog = page.getByRole('dialog', { name: 'Upload Logo', exact: true });
  await expect(logoDialog).toBeVisible();
  await settleVisualState(page);
  await page.screenshot({ path: testInfo.outputPath('website-file-modal-open.png'), fullPage: true });
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64');
  await logoDialog.locator('input[type=file]').setInputFiles({ name: 'logo.png', mimeType: 'image/png', buffer: png });
  await expect(logoDialog).toBeHidden();
  await expect(page.getByRole('img', { name: 'Logo', exact: true })).toBeVisible();
  const catalogue = page.waitForResponse(response => response.url().endsWith('/api/vault/sites/catalogue/snapshot'));
  const catalogueStart = Date.now();
  await page.getByRole('tab', { name: 'Pages', exact: true }).click();
  expect((await catalogue).ok()).toBe(true);
  const catalogueMs = Date.now() - catalogueStart; expect(catalogueMs).toBeLessThan(15_000);
  await testInfo.attach('catalogue-latency', { body: JSON.stringify({ milliseconds: catalogueMs }), contentType: 'application/json' });
  await page.getByRole('button', { name: 'Add page', exact: true }).click();
  await page.getByRole('button', { name: 'Add block', exact: true }).last().click();
  await page.getByLabel('Block type', { exact: true }).last().selectOption('cta');
  await page.getByRole('button', { name: 'Upload Link', exact: true }).click();
  const fileDialog = page.getByRole('dialog', { name: 'Upload Link', exact: true });
  await fileDialog.locator('input[type=file]').setInputFiles({ name: 'guide.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\nDisposable public fixture') });
  await expect(fileDialog).toBeHidden();
  const download = page.locator('.websites-asset-link'); await expect(download).toBeVisible();
  const saved = page.waitForEvent('download'); await download.click();
  expect((await saved).suggestedFilename()).toMatch(/\.pdf$/u);
  await expect(page.getByText('Saved', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('website-file-modal-preview.png'), fullPage: true });
  await page.reload(); await page.getByRole('tab', { name: 'Pages', exact: true }).click();
  await expect(page.locator('.websites-asset-link')).toBeVisible();
  await expect(page.getByLabel('Link', { exact: true })).toHaveValue(/\.pdf$/u);
  await page.getByRole('button', { name: 'Delete website', exact: true }).click();
  await page.getByRole('dialog', { name: 'Delete website', exact: true }).getByRole('button', { name: 'Delete', exact: true }).click();
});

import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';
import { installDisposableNetwork, seedDisposableBrowser } from '../../support/disposable-web.ts';

const dashboard = { id: 'bookmark-dashboard', title: 'Research overview', folder: '.Dashboards/Legacy', metadata: { icon: '📊' } };
const notes = Array.from({ length: 1200 }, (_, i) => ({ id: `bookmark-note-${i}`, title: i === 1199 ? 'Ètica de la cura' : `Reference ${i}`, metadata: {}, folder: 'Research' }));
const openNote = { id: 'synthetic-page', title: 'Synthetic acceptance note', metadata: { icon: '🧠' }, folder: '', content: '# Introduction\n\nSome content\n\n## Conclusion\n\nFinal paragraph ^ending' };

for (const theme of ['light', 'dark'] as const) {
  test(`bookmarks support searchable notes, dashboards, groups and views in ${theme}`, async ({ context, page }, testInfo) => {
    const audit = await installDisposableNetwork(context, { sidebarTree: [openNote, dashboard, ...notes] });
    await seedDisposableBrowser(context);
    await context.addInitScript(value => { localStorage.setItem('db-theme', value); }, theme);
    await context.route('**/api/vault/search?**', route => route.fulfill({ json: { results: [], total: 0, offset: 0, limit: 50 } }));
    await context.route('**/api/vault/pages/synthetic-page', route => route.fulfill({ json: openNote }));
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/@synthetic/knowledge', { waitUntil: 'domcontentloaded' });
    await expect(page.locator('.vault-shell__main')).toBeVisible({ timeout: 30_000 });
    await page.getByRole('button', { name: /tanca les notes|close release notes/i }).click({ timeout: 1500 }).catch(() => {});
    const bookmarks = page.getByRole('region', { name: 'Marcadors', exact: true });
    await bookmarks.getByRole('button', { name: 'Afegeix un marcador', exact: true }).first().click();
    let dialog = page.getByRole('dialog', { name: 'Afegeix un marcador', exact: true });
    await expect(dialog).toBeVisible();
    await dialog.getByLabel('Tipus', { exact: true }).selectOption('page');
    await dialog.getByRole('combobox', { name: 'Cerca una nota' }).fill('etica cura');
    await expect(dialog.getByRole('listbox').getByRole('option')).toHaveCount(1);
    await dialog.getByRole('combobox', { name: 'Cerca una nota' }).press('Enter');
    await expect(dialog.getByLabel('Nom', { exact: true })).toHaveValue('Ètica de la cura');
    await dialog.getByLabel('Grup', { exact: true }).fill('Lectures');
    await dialog.screenshot({ path: testInfo.outputPath(`bookmark-note-${theme}.png`) });
    const accessibility = await new AxeBuilder({ page }).include('[role="dialog"]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    expect(accessibility.violations).toEqual([]);
    await dialog.getByRole('button', { name: 'Desar', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await expect(bookmarks.getByRole('button', { name: 'Ètica de la cura', exact: true })).toBeVisible();
    await bookmarks.getByRole('button', { name: 'Afegeix un marcador', exact: true }).first().click();
    dialog = page.getByRole('dialog', { name: 'Afegeix un marcador', exact: true });
    await dialog.getByLabel('Tipus', { exact: true }).selectOption('dashboard');
    await dialog.getByRole('combobox', { name: 'Cerca un taulell' }).fill('Research');
    await dialog.getByRole('option', { name: 'Research overview' }).click();
    await dialog.getByRole('button', { name: 'Lectures', exact: true }).click();
    await dialog.getByRole('button', { name: 'Desar', exact: true }).click();
    await expect(bookmarks.getByRole('button', { name: 'Research overview', exact: true })).toBeVisible();
    await bookmarks.getByRole('textbox', { name: 'Cerca un marcador' }).fill('research');
    await expect(bookmarks.getByRole('button', { name: 'Ètica de la cura', exact: true })).toHaveCount(0);
    await expect(bookmarks.getByRole('button', { name: 'Research overview', exact: true })).toBeVisible();
    await bookmarks.getByRole('textbox', { name: 'Cerca un marcador' }).fill('');
    await bookmarks.getByRole('button', { name: /^Lectures\s*2$/ }).click();
    await expect(bookmarks.getByRole('button', { name: 'Research overview', exact: true })).toHaveCount(0);
    await bookmarks.getByRole('button', { name: /^Lectures\s*2$/ }).click();
    await bookmarks.getByRole('button', { name: 'Afegeix un marcador', exact: true }).first().click();
    dialog = page.getByRole('dialog', { name: 'Afegeix un marcador', exact: true });
    await dialog.getByLabel('Tipus', { exact: true }).selectOption('route');
    await dialog.getByRole('button', { name: 'Calendari', exact: true }).click();
    await dialog.getByRole('button', { name: 'Desar', exact: true }).click();
    await expect(bookmarks.getByRole('link', { name: 'Calendari', exact: true })).toHaveAttribute('href', '/@synthetic/calendar');
    await bookmarks.getByRole('button', { name: 'Afegeix un marcador', exact: true }).first().click();
    dialog = page.getByRole('dialog', { name: 'Afegeix un marcador', exact: true });
    await page.setViewportSize({ width: 390, height: 740 });
    const bounds = await dialog.boundingBox();
    expect(bounds).not.toBeNull();
    expect(bounds!.width).toBeLessThanOrEqual(390);
    expect(bounds!.height).toBeLessThanOrEqual(740);
    await expect(dialog.getByRole('button', { name: 'Cancel·lar', exact: true })).toBeInViewport();
    await dialog.screenshot({ path: testInfo.outputPath(`bookmark-mobile-${theme}.png`) });
    await page.keyboard.press('Escape');
    await expect(dialog).toHaveCount(0);
    expect(errors).toEqual([]);
    expect(audit.externalRequests).toEqual([]);
    expect(audit.unknownApiRequests).toEqual([]);
  });
}

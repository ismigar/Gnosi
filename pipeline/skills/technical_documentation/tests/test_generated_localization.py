@pytest.mark.parametrize(
    ("target", "title", "groups", "header", "regenerate"),
    [
        ("ca", "Catàleg de mòduls del backend", "Grups de mòduls",
         "| Grup | Mòduls | Línies |", "Regenera amb"),
        ("es", "Catálogo de módulos del backend", "Grupos de módulos",
         "| Grupo | Módulos | Líneas |", "Regenera con"),
        ("fr", "Catalogue des modules backend", "Groupes de modules",
         "| Groupe | Modules | Lignes |", "Régénérer avec"),
    ],
)
def test_fixed_labels_change_but_technical_bytes_never_do(
    target: str, title: str, groups: str, header: str, regenerate: str,
) -> None:
    translated = localize_generated_reference(FIXTURE, target, "backend-modules.md")
    text = translated.decode()
    assert f"# {title}\r\n" in text
    assert f"## {groups}\r\n" in text
    assert header + "\r\n" in text
    assert f"{regenerate} `python pipeline/skills/technical_documentation/scripts/generate.py`." in text
    assert DATA_ROW.encode() in translated
    assert b"| `Module groups` | 001 | 800 |\r\n" in translated
    assert b"\r\n## Module groups\r\n\r\n" in translated  # Source-derived heading collision.
    assert translated.split(b"---\r\n", 2)[:2] == FIXTURE.split(b"---\r\n", 2)[:2]
    assert translated[translated.index(b"````markdown"):] == FIXTURE[FIXTURE.index(b"````markdown"):]
    assert re.findall(rb"`[^`\r\n]+`", translated) == re.findall(rb"`[^`\r\n]+`", FIXTURE)
    assert re.findall(rb"https?://[^\s)]+", translated) == re.findall(rb"https?://[^\s)]+", FIXTURE)
    assert re.findall(rb"\d+", translated) == re.findall(rb"\d+", FIXTURE)
    assert translated.count(b"\r\n") == FIXTURE.count(b"\r\n")
    assert not translated.endswith(b"\n")
    assert localize_generated_reference(translated, target, "backend-modules.md") == translated


@pytest.mark.parametrize("target", ["ca", "es", "fr"])
def test_generated_refresh_preserves_reviewed_bytes_and_is_idempotent(
    target: str, locale_tree: Path, monkeypatch: pytest.MonkeyPatch,
) -> None:
    def forbidden(*args: object, **kwargs: object) -> None:
        pytest.fail("Generated-only refresh must not enter translation/configuration code")

    monkeypatch.setattr(localize, "OfflineTranslator", forbidden)
    monkeypatch.setattr(localize, "write_locale_config", forbidden)
    before = snapshot(locale_tree)
    assert localize.main(["--locale", target, "--generated-only"]) == 0
    first = snapshot(locale_tree)
    for relative, content in before.items():
        assert first[relative] == content
    expected_root = localize.LOCALES[target]["docs_root"] / "generated"
    output = expected_root / "backend-modules.md"
    assert output.read_bytes() == localize_generated_reference(FIXTURE, target, output.name)
    assert (expected_root / "evidence.bin").read_bytes() == b"\x00\xff\r\n001"
    times = {path: path.stat().st_mtime_ns for path in expected_root.iterdir()}
    assert localize.main(["--locale", target, "--generated-only"]) == 0
    assert snapshot(locale_tree) == first
    assert {path: path.stat().st_mtime_ns for path in times} == times
    assert localize.main(["--locale", target, "--check"]) == 0
    assert snapshot(locale_tree) == first


@pytest.mark.parametrize("target", ["ca", "es", "fr"])
@pytest.mark.parametrize("mutation", ["old-count", "mangled-label", "english-copy", "newline"])
def test_existing_stale_catalog_fails_read_only_check(
    target: str, mutation: str, locale_tree: Path,
) -> None:
    localize.generate_locale(target, generated_only=True)
    output = localize.LOCALES[target]["docs_root"] / "generated" / "backend-modules.md"
    valid = output.read_bytes()

def test_pre_pr_refreshes_locales_after_new_english_bytes(
    locale_tree: Path, monkeypatch: pytest.MonkeyPatch,
) -> None:
    for target in localize.LOCALES:
        localize.generate_locale(target, generated_only=True)
    fresh = FIXTURE.replace(b"| 800 |", b"| 801 |")

    def run_fixture_command(
        arguments: tuple[str, ...], *, cwd: Path, env: dict[str, str], check: bool,
    ) -> None:
        if arguments[1].endswith("generate.py"):
            source = localize.SOURCE_ROOT / "generated" / "backend-modules.md"
            if "--check" in arguments:
                assert source.read_bytes() == fresh
            else:
                source.write_bytes(fresh)
        else:
            assert localize.main(list(arguments[2:])) == 0

    monkeypatch.setattr(
        "pipeline.skills.technical_documentation.scripts.pre_pr.subprocess.run",
        run_fixture_command,
    )
    commands = [
        command for command in pre_pr.build_commands(base_ref=None, check_only=False)
        if command.arguments[1].endswith(("generate.py", "localize.py"))
    ]
    pre_pr.run_gate(commands)
    for target in localize.LOCALES:
        output = localize.LOCALES[target]["docs_root"] / "generated" / "backend-modules.md"
        assert output.read_bytes() == localize_generated_reference(fresh, target, output.name)


def test_generated_commands_never_import_models_or_application(locale_tree: Path) -> None:
    """A fresh process rejects imports even if the model is already cached locally."""
    script = """
import importlib.abc
from pathlib import Path
import sys
class ForbidRuntime(importlib.abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        if fullname.split('.')[0] in {'torch', 'transformers', 'backend', 'sentencepiece',
                                      'huggingface_hub', 'fastapi', 'sqlalchemy'}:
            raise AssertionError('Forbidden runtime import: ' + fullname)
sys.meta_path.insert(0, ForbidRuntime())
from pipeline.skills.technical_documentation.scripts import localize
root = Path(sys.argv[1])
localize.APP_ROOT = root
localize.SOURCE_ROOT = root / 'docs' / 'engineering'
for target, config in localize.LOCALES.items():
    config['docs_root'] = root / 'docs' / ('engineering-' + target)
    config['config'] = root / ('mkdocs-' + target + '.yml')
assert localize.main(['--generated-only']) == 0
assert localize.main(['--check']) == 0
assert localize.main(['--generated-only']) == 0
"""
    environment = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}
    app_root = Path(__file__).resolve().parents[4]
    subprocess.run(
        [sys.executable, "-B", "-c", script, str(locale_tree)],
        cwd=app_root, env=environment, check=True, capture_output=True, text=True,
    )
    assert localize.main(["--check"]) == 0
    # Also exercise the direct-script import branch without generating real outputs.
    subprocess.run(
        [sys.executable, "-B", str(app_root / "pipeline/skills/technical_documentation/scripts/localize.py"),
         "--help"],
        cwd=locale_tree, env=environment, check=True, capture_output=True, text=True,
    )

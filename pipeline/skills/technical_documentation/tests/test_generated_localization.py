@pytest.mark.parametrize("target", ["ca", "es", "fr"])
def test_every_generator_template_localizes_without_changing_its_data(
    target: str, tmp_path: Path,
) -> None:
    """Exercise actual English builders exclusively on synthetic source fixtures."""
    sources = {
        "backend/server.py": (
            "raise RuntimeError('must never import the application')\n"
            "@app.get('/api/pages/{page_id}')\n"
            "def get_page_v2():\n    '''Return Source | 42.'''\n    pass\n"
        ),
        "backend/models/page.py": (
            "class Page:\n    __tablename__ = 'pages_v2'\n"
            "    id: Mapped[int] = mapped_column(primary_key=True)\n"
            "    title: Mapped[str | None] = mapped_column(default='Source')\n"
        ),
        "frontend/src/Source groups/page.ts": (
            "export const get_page_v2 = '/api/pages/{page_id}?limit=100';\n"
        ),
        "frontend/src/App.tsx": (
            "import { Route } from 'react-router-dom';\n"
            "function Page() { return null; }\n"
            "export const App = () => <Route path='/pages/:page_id' element={<Page />} />;\n"
        ),
        "pipeline/skills/fixture/SKILL.md": "# Summary\n",
        "backend/tests/test_source.py": "def test_source():\n    pass\n",
        "domains.json": "[]",
    }
    for relative, content in sources.items():
        path = tmp_path / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    outputs = build_outputs(tmp_path, tmp_path, tmp_path / "domains.json")
    assert set(outputs) == set(PAGE_LABELS)
    for filename, english in outputs.items():
        translated = localize_generated_reference(english.encode(), target, filename).decode()
        assert translated != english
        assert f"# {PAGE_LABELS[filename][0]}\n" not in translated
        original_lines = english.splitlines()
        translated_lines = translated.splitlines()
        assert len(original_lines) == len(translated_lines)
        for index, line in enumerate(original_lines):
            if line.startswith("|") and not (
                index + 1 < len(original_lines) and original_lines[index + 1].startswith("| ---")
            ):
                assert translated_lines[index] == line
        assert re.findall(r"`[^`\n]+`", translated) == re.findall(r"`[^`\n]+`", english)


